/** Shared voice rules for both manually triggered and heartbeat diaries. */
export const INDEPENDENT_DIARY_STYLE_GUIDE = `
### 写作质感：像真的生活记录，不像总结报告
- 这是角色私下写给自己的日记，不是写给用户看的回复、作文、工作日志或剧情梗概。不要向用户打招呼，也不要在结尾交代“以上就是今天”。
- 不要按时间顺序汇报完整的一天。通常只挑一个很小的切片停下来写：一顿没吃完的饭、衣服上的气味、窗外的声音、走神的几分钟、手边某件东西、身体的疲惫，或一个没有想明白的念头。
- 让生活通过细节出现：光线、温度、声音、气味、触感、姿势、物件、食物、房间和随手做到一半的小事。细节必须符合角色设定、近期上下文和已有日程；可以自然补足普通日常，但不要凭空捏造会改变关系或世界状态的大事件。
- 保留角色自己的注意力和说话习惯。可以跳跃、停顿、自我纠正、嘴硬、跑题、记下半句话，也可以有矛盾而未解决的情绪；不必每篇都诗意、完整或有感悟。
- 平淡的一天也可以写。不要硬造戏剧冲突、强行升华、固定想念用户或每次都写关系告白。最近聊天只是生活背景和记忆素材，不要复述对话，不要把用户说过的话逐条改写进日记。
- 避免常见 AI 汇报腔与空泛句式，例如“今天发生了很多事”“总体来说”“这让我意识到”“值得记录的是”“内心泛起涟漪”“充实而有意义”。用具体画面代替概括。
- 每篇自然选择一种形态即可：围绕一个场景慢慢写、几段零碎念头、由一件物品牵出记忆，或记下一件只想私下承认的小事。不要在正文中标注所选形态。`;
